#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadLedger } from './ledger.mjs';

export function renderStatus(records) {
  const rows = records
    .map(
      ({ item, replay }) =>
        `| ${item.id} | ${item.state} | ${item.dependencies.join(', ') || '—'} | ${replay.claim?.claim_id ?? '—'} |`,
    )
    .join('\n');
  return `<!-- Generated by scripts/governance/generate-views.mjs; canonical sources are work/items and work/evidence. -->\n# Work status (informative)\n\nThis projection is non-canonical. G2a is **non-release and not alpha-eligible**.\n\n| Work item | State | Dependencies | Active claim |\n| --- | --- | --- | --- |\n${rows || '| — | — | — | — |'}\n`;
}

export function renderDependencyGraph(records) {
  const lines = [
    '<!-- Generated by scripts/governance/generate-views.mjs; canonical sources are work/items and work/evidence. -->',
    '# Work dependencies (informative)',
    '',
    'This projection is non-canonical. G2a is **non-release and not alpha-eligible**.',
    '',
    '```mermaid',
    'flowchart TD',
  ];
  for (const { item } of records) {
    lines.push(`  ${item.id.replaceAll('-', '_')}["${item.id}: ${item.state}"]`);
    for (const dependency of item.dependencies) {
      lines.push(`  ${dependency.replaceAll('-', '_')} --> ${item.id.replaceAll('-', '_')}`);
    }
  }
  lines.push('```', '');
  return lines.join('\n');
}

export function generatedViews(records) {
  return new Map([
    ['work/views/status.md', renderStatus(records)],
    ['work/views/dependency-graph.md', renderDependencyGraph(records)],
  ]);
}

export function main() {
  const root = resolve('.');
  const check = process.argv.includes('--check');
  const ledger = loadLedger(root);
  if (ledger.errors.length) {
    throw new Error(`Cannot generate views while canonical ledger is invalid:\n${ledger.errors.join('\n')}`);
  }
  const drift = [];
  for (const [path, content] of generatedViews(ledger.records)) {
    const fullPath = resolve(root, path);
    const actual = readFileSync(fullPath, 'utf8');
    if (actual !== content) {
      if (check) drift.push(path);
      else writeFileSync(fullPath, content);
    }
  }
  if (drift.length) {
    throw new Error(
      `Generated governance views drifted: ${drift.join(', ')}. Run node scripts/governance/generate-views.mjs.`,
    );
  }
  console.log(check ? 'Generated governance views are current.' : 'Generated governance views written.');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
